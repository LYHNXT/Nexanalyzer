"""Generate the synthetic validated cases next to this file.

    python tests/golden/cases/spectral_fit/make_synthetic.py

Each case is a true Voigt (lmfit's own lineshape, so the fitter's model and
the data agree exactly) on a flat baseline with 0.5 % seeded noise, and its
`expected.json` holds the generating parameters: that is the independent
reference the runner requires (tests/golden/README.md, "the generating
function and its parameters"). Peak centres sit exactly on a grid point, so
the sampled maximum `peak_intensity` reads equals the analytic height
(REVIEW.md 2026-11-04 #3 is about centres that do not).

The noise is there so the despiker sees a realistic MAD: on a noiseless peak
the whole band scores as a cosmic ray.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from lmfit.lineshapes import voigt

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3]))

from modules.spectra.processing.fitting import voigt_fwhm  # noqa: E402

#: 0.5 % of the tallest peak. Enough to give the despiker a realistic MAD (the
#: band then scores ~200 against the block's 500), small enough that the
#: portable tolerances (centre 0.1, FWHM 0.05, 1 % on height and area) hold.
NOISE_FRACTION = 0.005
SEED = 20261104


def _height(area: float, sigma: float, gamma: float) -> float:
    return float(voigt(np.array([0.0]), area, 0.0, sigma, gamma)[0])


def _block(mode: str, templates: list[dict]) -> dict:
    return {
        "x_range_enabled": False, "x_min": None, "x_max": None,
        "despike_threshold": 500.0,
        "baseline_algorithm": "None (Skip)",
        "baseline_degree": None, "baseline_lambda": None, "baseline_p": None,
        "peak_templates": templates,
        "exclusion_ranges": None,
        "max_iterations": 2000,
    }


def _write_case(name: str, mode: str, x: np.ndarray, peaks: list[dict], templates: list[dict]) -> None:
    """`peaks`: [{"label", "center", "sigma", "gamma", "area"}], centres on the grid."""
    rng = np.random.default_rng(SEED)
    y = np.zeros_like(x)
    for p in peaks:
        assert np.isclose(np.abs(x - p["center"]).min(), 0.0), f"{p['label']} centre is not on the grid"
        y += voigt(x, p["area"], p["center"], p["sigma"], p["gamma"])
    y += rng.normal(0.0, NOISE_FRACTION * y.max(), size=x.size)

    case = HERE / name
    case.mkdir(exist_ok=True)
    (case / "input.txt").write_text(
        "\n".join(f"{xi:.4f}\t{yi:.4f}" for xi, yi in zip(x, y)) + "\n", encoding="utf-8")

    block_key = "raman" if mode == "Raman" else "pl"
    (case / "settings.json").write_text(json.dumps({
        "mode": mode,
        "preset": {
            "material_name": f"Synthetic {mode}",
            "enabled": True,
            "description": "synthetic validated case; see make_synthetic.py",
            block_key: _block(mode, templates),
        },
    }, indent=2) + "\n", encoding="utf-8")

    unit = "cm-1" if mode == "Raman" else "nm"
    expected_peaks = {}
    for p in peaks:
        fwhm = voigt_fwhm(p["sigma"], p["gamma"])
        height = _height(p["area"], p["sigma"], p["gamma"])
        # 1 % on height and area for a strong peak; a weak narrow one (B2g at
        # ~5 points across its width, SNR ~60) states 3 %, which is still well
        # under the ~30 % by which a width mix-up or an area/height confusion
        # would move it.
        rel = p.get("rel_tol", 0.01)
        expected_peaks[p["label"]] = {
            "center": [round(p["center"], 4), 0.1],
            "fwhm": [round(fwhm, 4), 0.05],
            "intensity": [round(height, 4), round(rel * height, 4)],
            "area": [float(p["area"]), rel * p["area"]],
        }
    params = "; ".join(
        f"{p['label']}: center {p['center']} {unit}, sigma {p['sigma']}, gamma {p['gamma']}, area {p['area']}"
        for p in peaks)
    (case / "expected.json").write_text(json.dumps({
        "reference": (
            f"Synthetic: lmfit.lineshapes.voigt(x, area, center, sigma, gamma) with {params}; "
            f"flat baseline, {NOISE_FRACTION:.0%} Gaussian noise, seed {SEED}; "
            f"FWHM from fitting.voigt_fwhm, intensity the analytic Voigt height. "
            f"Generated by tests/golden/cases/spectral_fit/make_synthetic.py (2026-11-04)."
        ),
        "mode": mode,
        "r_squared_min": 0.99,
        "peaks": expected_peaks,
    }, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    # Raman: WSe2-like E2g+A1g (narrow) and B2g (weak, narrow) on a 0.9 cm-1 grid.
    x = 100.0 + 0.9 * np.arange(334)                      # 100 .. 399.7
    _write_case("synthetic_raman_voigt", "Raman", x,
                peaks=[
                    {"label": "E2g+A1g", "center": float(x[167]), "sigma": 1.0, "gamma": 1.5, "area": 5000.0},
                    {"label": "B2g", "center": float(x[231]), "sigma": 1.2, "gamma": 1.0, "area": 1500.0,
                     "rel_tol": 0.03},
                ],
                templates=[
                    {"peak_label": "E2g+A1g", "center": 250.0, "center_tolerance": 5.0,
                     "width_fwhm": 5.0, "shape": 0.5, "color": "#1f77b4"},
                    {"peak_label": "B2g", "center": 308.0, "center_tolerance": 5.0,
                     "width_fwhm": 5.0, "shape": 0.5, "color": "#ff7f0e"},
                ])
    # PL: one WSe2-like exciton at 755 nm on a 0.5 nm grid.
    x = 700.0 + 0.5 * np.arange(241)                      # 700 .. 820
    _write_case("synthetic_pl_voigt", "PL", x,
                peaks=[{"label": "Exciton", "center": float(x[110]), "sigma": 6.0, "gamma": 4.0, "area": 20000.0}],
                templates=[{"peak_label": "Exciton", "center": 757.0, "center_tolerance": 15.0,
                            "width_fwhm": 20.0, "shape": 0.5, "color": "#1f77b4"}])


if __name__ == "__main__":
    main()
